-- Equipment-specific safety requirements, verified completion history, QR custody and access audit.
alter table public.equipment add column if not exists qr_code text;
update public.equipment set qr_code='LABLINK-EQ-' || lpad(id::text,6,'0') where qr_code is null or qr_code='';
create unique index if not exists equipment_qr_code_unique on public.equipment(qr_code);

create table if not exists public.equipment_training_requirements (
  id bigint generated by default as identity primary key,
  equipment_id integer not null references public.equipment(id) on delete cascade,
  name text not null,
  description text not null default '',
  mandatory boolean not null default true,
  requires_supervision boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(equipment_id,name)
);

create table if not exists public.training_completions (
  id bigint generated by default as identity primary key,
  user_id integer not null references public.users(id),
  requirement_id bigint not null references public.equipment_training_requirements(id),
  completed_at timestamptz not null default now(),
  verified_by integer references public.users(id),
  verification_note text not null default '',
  method text not null default 'staff_verified',
  unique(user_id,requirement_id)
);
create index if not exists training_completion_history on public.training_completions(user_id,completed_at desc);

create table if not exists public.access_history (
  id bigint generated by default as identity primary key,
  user_id integer not null references public.users(id),
  equipment_id integer not null references public.equipment(id),
  booking_id integer references public.bookings(id),
  actor_id integer references public.users(id),
  action text not null,
  details jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);
create index if not exists access_history_equipment on public.access_history(equipment_id,occurred_at desc);

insert into public.equipment_training_requirements(equipment_id,name,description,mandatory,requires_supervision)
select e.id,e.name || ' safety certification','Required safety and operating procedure for ' || e.name || '.',true,
       e.name ilike '%CNC%' or e.name ilike '%Laser Cutter%'
from public.equipment e where e.training_required=1
on conflict(equipment_id,name) do nothing;

insert into public.training_completions(user_id,requirement_id,completed_at,method)
select t.user_id,r.id,t.completed_at,'legacy_record'
from public.training t join public.equipment_training_requirements r on r.equipment_id=t.equipment_id
on conflict(user_id,requirement_id) do nothing;

alter table public.equipment_training_requirements enable row level security;
alter table public.training_completions enable row level security;
alter table public.access_history enable row level security;
grant select,insert,update,delete on public.equipment_training_requirements,public.training_completions,public.access_history to service_role;
grant usage,select on all sequences in schema public to service_role;

create or replace view public.equipment_catalog
with (security_invoker = true) as
select e.id,e.name,e.category,e.location,e.description,e.specs,e.total_units,e.training_required,
       e.status,e.tags,e.operational_status,e.restrictions,e.max_hours,e.equivalent_group,
       e.technical_profile,d.name as department,d.code as department_code,e.qr_code
from public.equipment e join public.departments d on d.id=e.department_id;
grant select on public.equipment_catalog to anon,authenticated;
