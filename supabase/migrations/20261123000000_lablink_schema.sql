-- LabLink hosted schema for Supabase PostgreSQL.
-- Apply with `supabase db push` after linking a Supabase project.

create table if not exists public.departments (
  id integer generated by default as identity primary key,
  name text not null unique,
  code text not null unique
);

create table if not exists public.users (
  id integer generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  name text not null,
  department_id integer not null references public.departments(id),
  role text not null default 'student' check (role in ('student','project_team','faculty','technician','hod','admin'))
);

create table if not exists public.equipment (
  id integer generated by default as identity primary key,
  name text not null,
  category text not null,
  department_id integer not null references public.departments(id),
  location text not null,
  description text not null,
  specs text not null default '',
  total_units integer not null default 1 check (total_units > 0),
  training_required smallint not null default 0 check (training_required in (0,1)),
  status text not null default 'available',
  tags text not null default '[]',
  operational_status text not null default 'operational' check (operational_status in ('operational','maintenance','out_of_service')),
  restrictions text not null default '',
  max_hours integer not null default 8 check (max_hours between 1 and 24),
  equivalent_group text not null default '',
  technical_profile text not null default '{}'
);

create table if not exists public.projects (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id),
  name text not null,
  description text not null,
  deadline date not null,
  requirements text not null default '[]'
);

create table if not exists public.bookings (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id),
  project_id integer not null references public.projects(id),
  equipment_id integer not null references public.equipment(id),
  start_at text not null,
  end_at text not null,
  purpose text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected','cancelled','rescheduled','completed')),
  priority_score real not null default 0,
  fairness_note text not null default '',
  created_at timestamptz not null default now(),
  reviewed_by integer references public.users(id),
  review_note text not null default '',
  check (end_at > start_at)
);

create table if not exists public.training (
  user_id integer not null references public.users(id),
  equipment_id integer not null references public.equipment(id),
  completed_at timestamptz not null default now(),
  primary key (user_id,equipment_id)
);

create table if not exists public.audit_log (
  id integer generated by default as identity primary key,
  actor_id integer references public.users(id),
  action text not null,
  entity_type text not null,
  entity_id integer not null,
  details text not null default '{}',
  created_at timestamptz not null default now()
);

create table if not exists public.usage_events (
  id integer generated by default as identity primary key,
  equipment_id integer not null references public.equipment(id),
  user_id integer references public.users(id),
  booking_id integer references public.bookings(id),
  scheduled_start text,
  scheduled_end text,
  actual_start text,
  actual_end text,
  source text not null check (source in ('simulated','verified')),
  status text not null default 'complete',
  created_at timestamptz not null default now()
);

create table if not exists public.maintenance_logs (
  id integer generated by default as identity primary key,
  equipment_id integer not null references public.equipment(id),
  actor_id integer references public.users(id),
  note text not null,
  downtime_start text not null,
  downtime_end text,
  source text not null default 'verified',
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id),
  event_type text not null,
  title text not null,
  message text not null,
  entity_type text not null default 'system',
  entity_id integer,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  unique (user_id,event_type,entity_type,entity_id,created_at)
);

create index if not exists bookings_equipment_slot on public.bookings(equipment_id,start_at,end_at,status);
create unique index if not exists bookings_user_exact_slot on public.bookings(user_id,equipment_id,start_at,end_at) where status in ('pending','approved');
create index if not exists bookings_user_date on public.bookings(user_id,created_at);
create index if not exists projects_user_deadline on public.projects(user_id,deadline);
create index if not exists notifications_user_unread on public.notifications(user_id,created_at desc) where read_at is null;

create or replace function public.notify_booking_created()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.notifications(user_id,event_type,title,message,entity_type,entity_id)
  values (new.user_id,'booking_submitted','Request submitted','Your equipment request is pending approval.','booking',new.id);
  insert into public.notifications(user_id,event_type,title,message,entity_type,entity_id)
  select id,'booking_pending','New request to review','A student submitted an equipment request.','booking',new.id
  from public.users where role in ('faculty','hod','admin');
  return new;
end;
$$;

create or replace function public.notify_booking_status()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.status is distinct from new.status then
    insert into public.notifications(user_id,event_type,title,message,entity_type,entity_id)
    values (new.user_id,'booking_' || new.status,'Request ' || new.status,
      'Your booking request status changed to ' || new.status || '. ' || coalesce(new.review_note,''),'booking',new.id);
  end if;
  return new;
end;
$$;

create or replace function public.notify_equipment_updated()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if (old.operational_status,old.restrictions,old.total_units,old.training_required)
     is distinct from (new.operational_status,new.restrictions,new.total_units,new.training_required) then
    insert into public.notifications(user_id,event_type,title,message,entity_type,entity_id)
    select id,'equipment_updated','Equipment availability changed',new.name || ' status or access requirements were updated.','equipment',new.id
    from public.users where role in ('student','project_team');
  end if;
  return new;
end;
$$;

create or replace function public.notify_training_verified()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.notifications(user_id,event_type,title,message,entity_type,entity_id)
  values (new.user_id,'training_verified','Training verified','Your equipment safety training has been verified.','equipment',new.equipment_id);
  return new;
end;
$$;

drop trigger if exists notify_booking_created on public.bookings;
create trigger notify_booking_created after insert on public.bookings for each row execute function public.notify_booking_created();
drop trigger if exists notify_booking_status on public.bookings;
create trigger notify_booking_status after update of status on public.bookings for each row execute function public.notify_booking_status();
drop trigger if exists notify_equipment_updated on public.equipment;
create trigger notify_equipment_updated after update of operational_status,restrictions,total_units,training_required on public.equipment for each row execute function public.notify_equipment_updated();
drop trigger if exists notify_training_verified on public.training;
create trigger notify_training_verified after insert on public.training for each row execute function public.notify_training_verified();

-- Enable RLS everywhere. Public catalog access is read-only; private campus and
-- student records stay unavailable until authenticated policies are added.
alter table public.departments enable row level security;
alter table public.users enable row level security;
alter table public.equipment enable row level security;
alter table public.projects enable row level security;
alter table public.bookings enable row level security;
alter table public.training enable row level security;
alter table public.audit_log enable row level security;
alter table public.usage_events enable row level security;
alter table public.maintenance_logs enable row level security;
alter table public.notifications enable row level security;

grant usage on schema public to anon, authenticated;
grant select on public.departments, public.equipment to anon, authenticated;
grant select on public.departments, public.equipment, public.projects, public.bookings, public.training,
  public.audit_log, public.usage_events, public.maintenance_logs, public.notifications to service_role;
grant select, insert, update, delete on public.users to service_role;
grant select, insert, update, delete on public.departments, public.equipment, public.projects, public.bookings,
  public.training, public.audit_log, public.usage_events, public.maintenance_logs, public.notifications to service_role;
grant usage, select on all sequences in schema public to service_role;

create policy "Public catalog: departments" on public.departments for select to anon, authenticated using (true);
create policy "Public catalog: equipment" on public.equipment for select to anon, authenticated using (true);

create or replace view public.equipment_catalog
with (security_invoker = true) as
select e.id,e.name,e.category,e.location,e.description,e.specs,e.total_units,e.training_required,
       e.status,e.tags,e.operational_status,e.restrictions,e.max_hours,e.equivalent_group,
       e.technical_profile,d.name as department,d.code as department_code
from public.equipment e join public.departments d on d.id=e.department_id;
grant select on public.equipment_catalog to anon, authenticated;
