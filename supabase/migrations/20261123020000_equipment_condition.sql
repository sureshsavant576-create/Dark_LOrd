-- Equipment health and service history for projects that already applied the base schema.
alter table public.equipment
  add column if not exists condition_status text not null default 'available'
  check (condition_status in ('available','in_use','under_maintenance','under_inspection'));
update public.equipment set condition_status='under_maintenance'
where operational_status<>'operational' and condition_status='available';

create table if not exists public.equipment_condition_reports (
  id integer generated by default as identity primary key,
  equipment_id integer not null references public.equipment(id),
  reporter_id integer not null references public.users(id),
  report_type text not null check (report_type in ('fault','damage')),
  description text not null check (length(description) between 8 and 1000),
  photo_data text,
  status text not null default 'open' check (status in ('open','cleared')),
  created_at timestamptz not null default now(),
  cleared_by integer references public.users(id),
  cleared_at timestamptz
);
create index if not exists condition_reports_equipment_status
  on public.equipment_condition_reports(equipment_id,status,created_at desc);
alter table public.equipment_condition_reports enable row level security;
grant select, insert, update, delete on public.equipment_condition_reports to service_role;
grant usage, select on sequence public.equipment_condition_reports_id_seq to service_role;

create or replace view public.equipment_catalog
with (security_invoker = true) as
select e.id,e.name,e.category,e.location,e.description,e.specs,e.total_units,e.training_required,
       e.status,e.tags,e.operational_status,e.restrictions,e.max_hours,e.equivalent_group,
       e.technical_profile,d.name as department,d.code as department_code,e.condition_status,e.qr_code
from public.equipment e join public.departments d on d.id=e.department_id;
grant select on public.equipment_catalog to anon, authenticated;
